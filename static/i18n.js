let currentLanguage = 'en';

function detectInitialLanguage() {
    const supported = ['pt', 'en', 'es', 'fr', 'ru'];
    const saved = localStorage.getItem('erdown_lang');
    if (saved && supported.includes(saved)) {
        return saved;
    }

    const navLangs = navigator.languages ? navigator.languages : [navigator.language || 'en'];
    for (let l of navLangs) {
        if (!l) continue;
        const code = l.toLowerCase().split('-')[0];
        if (supported.includes(code)) {
            return code;
        }
    }

    return 'en';
}

function setLanguage(lang) {
    if (!EromeDown_TRANSLATIONS[lang]) {
        lang = 'en';
    }

    currentLanguage = lang;
    localStorage.setItem('erdown_lang', lang);
    document.documentElement.lang = lang;

    const dict = EromeDown_TRANSLATIONS[lang];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
}

function t(key) {
    if (EromeDown_TRANSLATIONS[currentLanguage] && EromeDown_TRANSLATIONS[currentLanguage][key]) {
        return EromeDown_TRANSLATIONS[currentLanguage][key];
    }
    if (EromeDown_TRANSLATIONS['en'] && EromeDown_TRANSLATIONS['en'][key]) {
        return EromeDown_TRANSLATIONS['en'][key];
    }
    return key;
}

document.addEventListener('DOMContentLoaded', () => {
    const lang = detectInitialLanguage();
    setLanguage(lang);

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const targetLang = btn.getAttribute('data-lang');
            if (targetLang) {
                setLanguage(targetLang);
            }
        });
    });
});
